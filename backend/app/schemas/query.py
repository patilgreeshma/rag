"""
app/schemas/query.py – Pydantic request / response models for the FinRule AI API.

Used by FastAPI for automatic request validation, response serialisation,
and OpenAPI (Swagger) documentation generation.
"""
from __future__ import annotations

from typing import Any, Optional

from pydantic import BaseModel, Field


# ── Request ───────────────────────────────────────────────────────────────────

class QueryRequest(BaseModel):
    """POST /query request body."""

    question: str = Field(
        ...,
        min_length=3,
        max_length=2000,
        description="Natural-language question about SEBI regulations.",
        examples=["What are the disclosure requirements under LODR?"],
    )
    top_k: int = Field(
        default=5,
        ge=1,
        le=20,
        description="Number of provision chunks to retrieve (1–20).",
    )

    model_config = {"json_schema_extra": {"example": {"question": "What is the definition of insider under PIT regulations?", "top_k": 5}}}


# ── Nested response types ─────────────────────────────────────────────────────

class SourceItem(BaseModel):
    """A single source document / provision cited in the answer."""

    title: Optional[str] = Field(None, description="Regulation / circular title.")
    section_number: Optional[str] = Field(None, description="Provision / section number.")
    section: Optional[str] = Field(None, description="Section heading.")
    document_type: Optional[str] = Field(None, description="Document type (regulatory, circular, …).")
    source_url: Optional[str] = Field(None, description="Official SEBI source URL.")
    in_force: bool = Field(True, description="Whether this instrument is currently in force.")
    score: float = Field(..., description="Similarity score (0–1).")


class ChunkItem(BaseModel):
    """A retrieved provision chunk (returned for debugging / transparency)."""

    chunk_id: str
    text: str
    score: float
    title: Optional[str] = None
    section_number: Optional[str] = None
    source_url: Optional[str] = None
    in_force: bool = True
    metadata: dict = Field(default_factory=dict)


# ── Response ──────────────────────────────────────────────────────────────────

class QueryResponse(BaseModel):
    """POST /query response body."""

    question: str = Field(..., description="The original question echoed back.")
    answer: str = Field(..., description="Grounded answer generated by Gemini.")
    sources: list = Field(
        default_factory=list,
        description="Cited source provisions (de-duplicated by URL).",
    )
    retrieved_chunks: list = Field(
        default_factory=list,
        description="All retrieved chunks above the similarity threshold.",
    )
    sufficient_context: bool = Field(
        ...,
        description="False if no chunks cleared the similarity threshold.",
    )
    top_score: Optional[float] = Field(
        None,
        description="Highest similarity score among retrieved chunks.",
    )


# ── Health ────────────────────────────────────────────────────────────────────

class HealthResponse(BaseModel):
    """GET /health response body."""

    status: str = "healthy"
    version: str = "1.0.0"
    index_vectors: int = Field(
        ..., description="Number of vectors in the FAISS index."
    )
